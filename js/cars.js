export const FORZA_CARS = LIST.map(([name, d]) => {
  const division = FORZA_DIVISIONS[d];
  const year = Number(name.slice(0, 4)) || null;
  return { name, division, year, raceCar: name.includes('#') || RACE_DIVISIONS.has(division) };
});

const norm = (s) => String(s || '').toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/[^a-z0-9]+/g, ' ').trim();
const BY_NAME = new Map(FORZA_CARS.map((c) => [norm(c.name), c]));

// The listed car with this exact name (ignoring case, accents and punctuation), or null.
export const findCar = (name) => BY_NAME.get(norm(name)) || null;

// Cars matching every word typed, shortest names first.
export function searchCars(q, limit = 20) {
  const words = norm(q).split(' ').filter(Boolean);
  if (!words.length) return [];
  // Each typed word must start a word in the name ("rs" finds "GT3 RS", not "Porsche").
  return FORZA_CARS.filter((c) => { const parts = norm(c.name).split(' '); return words.every((w) => parts.some((p) => p.startsWith(w))); })
    .sort((a, b) => a.name.length - b.name.length)
    .slice(0, limit);
}
